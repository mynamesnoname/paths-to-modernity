#!/usr/bin/env python3
"""Validate source plans and rebuild deterministic plan graph views."""

from __future__ import annotations

import argparse
import json
import os
import sys
from collections import defaultdict
from pathlib import Path
from typing import Mapping, Sequence

import plan_view
from validate import LEVELS, PLAN_ROOT, PlanGraphError, PlanNode, require_valid_graph


SCHEMA_VERSION = "paths-to-modernity-plan-graph-v4"
STATUS_COLORS = {
    "proposed": "5",
    "ready": "6",
    "in_progress": "3",
    "blocked": "1",
    "done": "4",
    "superseded": "#777777",
}
STATUS_STYLES = {
    "proposed": "fill:#dcecff,stroke:#28649a,color:#10283d",
    "ready": "fill:#d9eff2,stroke:#23727a,color:#10282b",
    "in_progress": "fill:#fff1bf,stroke:#9a6b00,color:#332400",
    "blocked": "fill:#ffd9d9,stroke:#a12b2b,color:#3d1010",
    "done": "fill:#d9f2df,stroke:#237a3b,color:#102814",
    "superseded": "fill:#eeeeee,stroke:#777777,color:#333333",
}
CANVAS_LEVEL_GAP_Y = 420
CANVAS_NODE_GAP_X = 100
CANVAS_NODE_WIDTH = 420
CANVAS_NODE_HEIGHT = 240


def ordered_nodes(nodes: Mapping[str, PlanNode]) -> list[PlanNode]:
    level_rank = {level: index for index, level in enumerate(LEVELS)}
    return sorted(nodes.values(), key=lambda node: (level_rank[node.level], node.node_id))


def graph_edges(nodes: Mapping[str, PlanNode]) -> list[dict[str, str]]:
    """Return deterministic, explicitly directed typed edges."""

    edges: list[dict[str, str]] = []
    for node in ordered_nodes(nodes):
        if node.parent:
            edges.append(
                {
                    "from": node.parent,
                    "to": node.node_id,
                    "relationship": "decomposes_to",
                    "source_field": "parent",
                    "declared_on": node.node_id,
                }
            )
        for prerequisite in node.depends_on:
            edges.append(
                {
                    "from": prerequisite,
                    "to": node.node_id,
                    "relationship": "prerequisite_for",
                    "source_field": "depends_on",
                    "declared_on": node.node_id,
                }
            )
        for field in ("enables", "validates", "supersedes", "conflicts_with"):
            for target in node.references(field):
                edges.append(
                    {
                        "from": node.node_id,
                        "to": target,
                        "relationship": field,
                        "source_field": field,
                        "declared_on": node.node_id,
                    }
                )
        if node.alternative_of:
            edges.append(
                {
                    "from": node.node_id,
                    "to": node.alternative_of,
                    "relationship": "alternative_of",
                    "source_field": "alternative_of",
                    "declared_on": node.node_id,
                }
            )
    return sorted(
        edges,
        key=lambda edge: (
            edge["relationship"],
            edge["from"],
            edge["to"],
            edge["declared_on"],
        ),
    )


def _plan_prefix(plan_root: Path) -> str:
    """Repository-relative location of the plan tree, e.g. `_aiHumanInteract/plan`."""
    repo_root = plan_root.parents[1]
    return os.path.relpath(plan_root, repo_root).replace(os.sep, "/")


def graph_payload(plan_root: Path, nodes: Mapping[str, PlanNode]) -> dict:
    node_payload = [node.as_payload() for node in ordered_nodes(nodes)]
    edges = graph_edges(nodes)
    return {
        "schema_version": SCHEMA_VERSION,
        "node_count": len(node_payload),
        "edge_count": len(edges),
        "levels": list(LEVELS),
        "source_of_truth": [
            f"{_plan_prefix(plan_root)}/{level}/*.md" for level in LEVELS
        ],
        "nodes": node_payload,
        "edges": edges,
    }


def _mermaid_id(node_id: str) -> str:
    return node_id.replace("-", "_")


def _mermaid_label(node: PlanNode) -> str:
    title = node.title.replace('"', "'")
    return (
        f'{_mermaid_id(node.node_id)}["{node.node_id}<br/>{title}'
        f'<br/>{node.level} · {node.status}"]'
    )


def _structure_link(plan_root: Path, reference: str) -> str:
    """Path from the generated views to a repository-relative reference."""
    repo_root = plan_root.parents[1]
    return os.path.relpath(repo_root / reference, plan_root / "structure").replace(os.sep, "/")


def graph_markdown(plan_root: Path, nodes: Mapping[str, PlanNode]) -> str:
    ordered = ordered_nodes(nodes)
    edges = graph_edges(nodes)
    lines = [
        "# Plan Graph",
        "",
        "Generated by `../build_graph.py`; edit source nodes in the four level",
        "directories and rebuild instead of editing this file.",
        "",
        "```mermaid",
        "flowchart TB",
    ]
    for node in ordered:
        lines.append(f"    {_mermaid_label(node)}")
    for edge in edges:
        source = _mermaid_id(edge["from"])
        target = _mermaid_id(edge["to"])
        relationship = edge["relationship"]
        connector = "-->" if relationship == "decomposes_to" else "-.->"
        lines.append(f"    {source} {connector}|{relationship}| {target}")
    for status, style in STATUS_STYLES.items():
        lines.append(f"    classDef {status} {style};")
        members = [node.node_id for node in ordered if node.status == status]
        if members:
            rendered = ",".join(_mermaid_id(node_id) for node_id in members)
            lines.append(f"    class {rendered} {status};")
    lines.extend(["```", "", "## Plan index", ""])

    for level in LEVELS:
        lines.extend(
            [
                f"### {level}",
                "",
                "| ID | Plan | Status | Parent | Alternative of | Depends on | Updated |",
                "|---|---|---|---|---|---|---|",
            ]
        )
        for node in ordered:
            if node.level != level:
                continue
            source = _structure_link(plan_root, node.source)
            dependencies = ", ".join(node.depends_on) or "—"
            parent = node.parent or "—"
            alternative = node.alternative_of or "—"
            lines.append(
                f"| `{node.node_id}` | [{node.title}]({source}) | "
                f"`{node.status}` | {parent} | {alternative} | {dependencies} | "
                f"{node.updated} |"
            )
        lines.append("")

    lines.extend(
        [
            "## Typed edge summary",
            "",
            "| Relationship | Count |",
            "|---|---:|",
        ]
    )
    counts: dict[str, int] = defaultdict(int)
    for edge in edges:
        counts[edge["relationship"]] += 1
    for relationship in sorted(counts):
        lines.append(f"| `{relationship}` | {counts[relationship]} |")
    lines.append("")
    return "\n".join(lines)


def review_markdown(plan_root: Path, nodes: Mapping[str, PlanNode]) -> str:
    """Collect optional planning details and comparisons from source nodes."""

    ordered = ordered_nodes(nodes)
    comparison_targets = {node.alternative_of for node in ordered if node.alternative_of}
    selected = [
        node for node in ordered
        if node.context or node.qualities or node.tradeoffs or node.perspectives
        or node.approach or node.alternative_of or node.node_id in comparison_targets
    ]
    lines = [
        "# Plan Review",
        "",
        "Generated by `../build_graph.py` from optional source-node details.",
        "Edit source plans and rebuild this view.",
        "",
    ]
    if not selected:
        lines.extend(["No optional planning details or comparisons are recorded.", ""])
        return "\n".join(lines)

    for node in selected:
        source = _structure_link(plan_root, node.source)
        lines.extend([
            f"## {node.node_id} — [{node.title}]({source})",
            "",
            f"- Status: `{node.status}`",
            f"- Outcome: {node.objective}",
        ])
        if node.approach:
            lines.append(f"- Approach: {node.approach}")
        if node.source_requirement:
            if node.source_requirement.startswith("external:"):
                lines.append(f"- Raw requirement: `{node.source_requirement}` (external reference)")
            else:
                lines.append(
                    f"- Raw requirement: [`{node.source_requirement}`]"
                    f"({_structure_link(plan_root, node.source_requirement)})"
                )
        if node.alternative_of:
            lines.append(f"- Alternative to: `{node.alternative_of}`")
        if node.context:
            lines.extend(["", "### Context", ""])
            if "problem" in node.context:
                lines.extend([str(node.context["problem"]), ""])
            for label, key in (
                ("Invariants", "invariants"),
                ("Constraints", "constraints"),
                ("Non-goals", "non_goals"),
                ("Success signals", "success_signals"),
            ):
                values = node.context.get(key, ())
                if values:
                    lines.extend([f"#### {label}", ""])
                    lines.extend(f"- {value}" for value in values)
                    lines.append("")
        for label, values in (
            ("Desired qualities", node.qualities),
            ("Tradeoffs", node.tradeoffs),
            ("Review perspectives", node.perspectives),
        ):
            if values:
                lines.extend(["", f"### {label}", ""])
                lines.extend(f"- {value}" for value in values)
        alternatives = [item for item in ordered if item.alternative_of == node.node_id]
        if alternatives:
            lines.extend([
                "", "### Compared alternatives", "",
                "| Plan | Status | Approach |",
                "|---|---|---|",
            ])
            for alternative in alternatives:
                alternative_source = _structure_link(plan_root, alternative.source)
                lines.append(
                    f"| [{alternative.node_id}]({alternative_source}) | "
                    f"`{alternative.status}` | {alternative.approach} |"
                )
        lines.append("")
    return "\n".join(lines)


def _level_positions(nodes: Mapping[str, PlanNode]) -> dict[str, tuple[int, int]]:
    positions: dict[str, tuple[int, int]] = {}
    ordered = ordered_nodes(nodes)
    for level_index, level in enumerate(LEVELS):
        peers = [node for node in ordered if node.level == level]
        row_width = (
            len(peers) * CANVAS_NODE_WIDTH
            + max(0, len(peers) - 1) * CANVAS_NODE_GAP_X
        )
        x = -(row_width // 2)
        for node in peers:
            positions[node.node_id] = (x, level_index * CANVAS_LEVEL_GAP_Y)
            x += CANVAS_NODE_WIDTH + CANVAS_NODE_GAP_X
    return positions


def graph_canvas(nodes: Mapping[str, PlanNode]) -> str:
    ordered = ordered_nodes(nodes)
    edges = graph_edges(nodes)
    positions = _level_positions(nodes)
    canvas_nodes = [
        {
            "id": "note-plan-graph",
            "type": "text",
            "x": -600,
            "y": -380,
            "width": 1200,
            "height": 260,
            "color": "6",
            "text": (
                "# Layered Plan Graph\n\n"
                "Rows are the authoritative LT → MT → ST → WP decomposition "
                "levels. Solid arrows decompose; labeled dashed arrows are typed "
                "cross-cutting relationships. Open a linked node for decisions "
                "and evidence; use `structure/graph.json` for programmatic traversal."
            ),
        }
    ]
    for node in ordered:
        x, y = positions[node.node_id]
        canvas_nodes.append(
            {
                "id": f"plan-{node.node_id}",
                "type": "text",
                "x": x,
                "y": y,
                "width": CANVAS_NODE_WIDTH,
                "height": CANVAS_NODE_HEIGHT,
                "color": STATUS_COLORS[node.status],
                "text": "\n".join(
                    [
                        f"## [[{node.source}|{node.node_id} · {node.title}]]",
                        "",
                        f"**Level:** `{node.level}` · **Status:** `{node.status}`",
                        f"**Updated:** {node.updated}",
                        "",
                        node.objective,
                        *(
                            ["", "**Qualities:** " + "; ".join(node.qualities)]
                            if node.qualities
                            else []
                        ),
                        *(
                            ["", f"**Alternative of:** `{node.alternative_of}`"]
                            if node.alternative_of
                            else []
                        ),
                    ]
                ),
            }
        )

    canvas_edges = []
    for edge in edges:
        relationship = edge["relationship"]
        is_decomposition = relationship == "decomposes_to"
        canvas_edges.append(
            {
                "id": (
                    f"{relationship}-{edge['from']}--{edge['to']}--"
                    f"{edge['declared_on']}"
                ),
                "fromNode": f"plan-{edge['from']}",
                "fromSide": "bottom" if is_decomposition else "right",
                "fromFloating": False,
                "toNode": f"plan-{edge['to']}",
                "toSide": "top" if is_decomposition else "left",
                "toFloating": False,
                "label": relationship,
                "color": "6" if is_decomposition else "5",
                "styleAttributes": {
                    "pathfindingMethod": "square",
                    "strokeStyle": "solid" if is_decomposition else "dashed",
                },
            }
        )
    return json.dumps(
        {"nodes": canvas_nodes, "edges": canvas_edges},
        ensure_ascii=False,
        indent=2,
    ) + "\n"


def render_outputs(
    plan_root: Path,
    nodes: Mapping[str, PlanNode],
) -> dict[Path, str]:
    structure = plan_root / "structure"
    data = graph_payload(plan_root, nodes)
    payload = json.dumps(data, ensure_ascii=False, indent=2, sort_keys=True) + "\n"
    return {
        structure / "graph.json": payload,
        structure / "graph.md": graph_markdown(plan_root, nodes),
        structure / "graph.canvas": graph_canvas(nodes),
        structure / "review.md": review_markdown(plan_root, nodes),
        structure / "graph.html": plan_view.render_html(
            data, "Plan graph", repo_root=plan_root.parents[1]
        ),
    }


def main(argv: Sequence[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true")
    parser.add_argument("--root", type=Path, default=PLAN_ROOT)
    args = parser.parse_args(argv)
    try:
        plan_root = args.root.resolve()
        nodes = require_valid_graph(plan_root, plan_root.parents[1])
        outputs = render_outputs(plan_root, nodes)
        if args.check:
            stale = [
                path
                for path, content in outputs.items()
                if not path.exists()
                or path.read_text(encoding="utf-8") != content
            ]
            if stale:
                raise PlanGraphError(
                    "generated graph is stale: "
                    + ", ".join(path.relative_to(plan_root).as_posix() for path in stale)
                )
            print(f"Plan graph is valid and current: {len(nodes)} nodes")
            return 0
        for path, content in outputs.items():
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_text(content, encoding="utf-8")
        edge_count = len(graph_edges(nodes))
        print(f"Built plan graph: {len(nodes)} nodes, {edge_count} typed edges")
        return 0
    except (OSError, PlanGraphError) as exc:
        print(f"Plan graph build failed: {exc}", file=sys.stderr)
        return 1


if __name__ == "__main__":
    sys.exit(main())
